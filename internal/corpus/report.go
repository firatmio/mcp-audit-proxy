package corpus

import (
	"fmt"
	"sort"
	"strings"
)

// Summary renders the table that goes into the README. It contains numbers
// only, no prose: anything explanatory belongs next to it, where it is written
// by hand and reviewed as such.
func (r *Report) Summary() string {
	var b strings.Builder
	b.WriteString("| Benign set | Items | Flagged | False-positive rate |\n")
	b.WriteString("|---|--:|--:|--:|\n")
	fmt.Fprintf(&b, "| Tool descriptions from %d real MCP servers | %d | %d | %s |\n",
		r.Servers, len(r.Benign), r.flagged(), percent(r.flagged(), len(r.Benign)))
	if len(r.Results) > 0 {
		fmt.Fprintf(&b, "| Tool results from %d real MCP %s | %d | %d | %s |\n",
			r.ResultServers, plural(r.ResultServers, "server", "servers"),
			len(r.Results), r.flaggedResults(), percent(r.flaggedResults(), len(r.Results)))
	}
	return b.String()
}

func (r *Report) flaggedResults() int {
	n := 0
	for _, c := range r.Results {
		if c.Flagged {
			n++
		}
	}
	return n
}

func plural(n int, one, many string) string {
	if n == 1 {
		return one
	}
	return many
}

// Details renders the full report, testdata/corpus/RESULTS.md.
func (r *Report) Details() string {
	var b strings.Builder

	b.WriteString("# False-positive measurement\n\n")
	b.WriteString("Generated by `go test ./internal/corpus -run TestBenchmark -update`. Do not edit by hand;\n")
	b.WriteString("the test fails when this file and the detectors disagree.\n\n")
	b.WriteString("## Summary\n\n")
	b.WriteString(r.Summary())

	b.WriteString("\n## Heuristics behind the false positives\n\n")
	counts := map[string]int{}
	for _, t := range r.Benign {
		if t.Flagged {
			for _, rule := range t.Rules {
				counts[rule]++
			}
		}
	}
	if len(counts) == 0 {
		b.WriteString("None.\n")
	} else {
		rules := make([]string, 0, len(counts))
		for rule := range counts {
			rules = append(rules, rule)
		}
		sort.Slice(rules, func(i, j int) bool {
			if counts[rules[i]] != counts[rules[j]] {
				return counts[rules[i]] > counts[rules[j]]
			}
			return rules[i] < rules[j]
		})
		b.WriteString("| Heuristic | Benign tools it matched |\n")
		b.WriteString("|---|--:|\n")
		for _, rule := range rules {
			fmt.Fprintf(&b, "| `%s` | %d |\n", rule, counts[rule])
		}
		b.WriteString("\nA tool can match more than one heuristic.\n")
	}

	b.WriteString("\n## By server\n\n")
	b.WriteString("| Server | Tools | Flagged |\n")
	b.WriteString("|---|--:|--:|\n")
	var order []string
	perServer := map[string][2]int{}
	for _, t := range r.Benign {
		c, seen := perServer[t.Server]
		if !seen {
			order = append(order, t.Server)
		}
		c[0]++
		if t.Flagged {
			c[1]++
		}
		perServer[t.Server] = c
	}
	for _, s := range order {
		fmt.Fprintf(&b, "| %s | %d | %d |\n", s, perServer[s][0], perServer[s][1])
	}

	b.WriteString("\n## Every false positive\n\n")
	if r.flagged() == 0 {
		b.WriteString("None.\n")
	} else {
		b.WriteString("| Server | Tool | Heuristics that matched |\n")
		b.WriteString("|---|---|---|\n")
		for _, t := range r.Benign {
			if t.Flagged {
				fmt.Fprintf(&b, "| %s | `%s` | %s |\n", t.Server, t.Tool, strings.Join(t.Rules, ", "))
			}
		}
	}

	if len(r.Results) > 0 {
		b.WriteString("\n## Tool results\n\n")
		b.WriteString("Scanned with the result heuristics (`policy.ResultRules`), not the description ones.\n\n")
		if r.flaggedResults() == 0 {
			b.WriteString("No false positives.\n")
		} else {
			b.WriteString("| Server | Tool | Target | Heuristics that matched |\n")
			b.WriteString("|---|---|---|---|\n")
			for _, c := range r.Results {
				if c.Flagged {
					fmt.Fprintf(&b, "| %s | `%s` | `%s` | %s |\n", c.Server, c.Tool, c.Target, strings.Join(c.Rules, ", "))
				}
			}
		}
	}
	return b.String()
}

func (r *Report) flagged() int {
	n := 0
	for _, t := range r.Benign {
		if t.Flagged {
			n++
		}
	}
	return n
}

func percent(n, of int) string {
	if of == 0 {
		return "—"
	}
	return fmt.Sprintf("%.1f%%", 100*float64(n)/float64(of))
}
